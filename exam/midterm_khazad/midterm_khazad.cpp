void gen_Kbox() {
    byte K[256];
    byte up1, low1, up2, low2, up3, low3;

    for (int i = 0; i < 256; i++) {
        up1 = i >> 4;
        low1 = i & 0x0f;
        up1 = P[up1];
        low1 = Q[low1];
        
        up2 = (up1 & 0x0c) | (low1 >> 2);
        low2 = ((up1 << 2) & 0xf) | (low1 & 0x03);
        up2 = Q[up2];
        low2 = P[low2];

        up3 = (up2 & 0x0c) | (low2 >> 2);
        low3 = ((up2 << 2) & 0xf) | (low2 & 0x03);
        up3 = P[up3];
        low3 = Q[low3];

        K[i] = (up3 << 4) | low3;
    }

    
    printf("byte K[256] = {\n");
    for (int i = 0; i < 256; i++) {
        if (i < 255) {
            printf("0x%02x, ", K[i]);
        }
        else {
            printf("0x%02x };\n", K[i]);
        }
        if ((i % 16) == 15) printf("\n");
    }
}


