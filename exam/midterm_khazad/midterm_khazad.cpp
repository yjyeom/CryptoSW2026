// 데이터 변환: 바이트 b[16] <--> 워드 state[4]
void byte2state(byte b[16], u32 st[4]) {
    st[0] = GETU32(b);
    st[1] = GETU32(b + 4);
    st[2] = GETU32(b + 8);
    st[3] = GETU32(b + 12);
}

void state2byte(u32 st[4], byte b[16]) {
    PUTU32(b, st[0]);
    PUTU32(b + 4, st[1]);
    PUTU32(b + 8, st[2]);
    PUTU32(b + 12, st[3]);
}

// SES8 용 키스케줄
void SES8_KeySchedule(byte k[16], byte rk[11][16]) {
    u32 rk32[11][4];

    SES32_Enc_KeySchedule(k, rk32);
    for (int i = 0; i < 11; i++) {
        state2byte(rk32[i], rk[i]);
    }
}

void SES32_EncRound(u32 st[4], u32 rk[4]) {
    u32 tmp[4];

    // Transpose를 적용하여 바이트를 선택
    tmp[0] = T0[(st[0] >> 24) & 0xff] ^ T1[(st[1] >> 24) & 0xff] ^ T2[(st[2] >> 24) & 0xff] ^ T3[(st[3] >> 24) & 0xff] ^ rk[0];
    tmp[1] = T0[(st[0] >> 16) & 0xff] ^ T1[(st[1] >> 16) & 0xff] ^ T2[(st[2] >> 16) & 0xff] ^ T3[(st[3] >> 16) & 0xff] ^ rk[1];
    tmp[2] = T0[(st[0] >> 8) & 0xff] ^ T1[(st[1] >> 8) & 0xff] ^ T2[(st[2] >> 8) & 0xff] ^ T3[(st[3] >> 8) & 0xff] ^ rk[2];
    tmp[3] = T0[st[0] & 0xff] ^ T1[st[1] & 0xff] ^ T2[st[2] & 0xff] ^ T3[st[3] & 0xff] ^ rk[3];
    for (int k = 0; k < 4; k++) {
        st[k] = tmp[k];
    }
}


void SES32_EqDecRound(u32 st[4], u32 rk[4]) {
    u32 tmp[4];

    // Transpose를 적용하여 바이트를 선택
    tmp[0] = T0[(st[0] >> 24) & 0xff] ^ T1[(st[1] >> 24) & 0xff] ^ T2[(st[2] >> 24) & 0xff] ^ T3[(st[3] >> 24) & 0xff] ^ rk[0];
    tmp[1] = T0[(st[0] >> 16) & 0xff] ^ T1[(st[1] >> 16) & 0xff] ^ T2[(st[2] >> 16) & 0xff] ^ T3[(st[3] >> 16) & 0xff] ^ rk[1];
    tmp[2] = T0[(st[0] >> 8) & 0xff] ^ T1[(st[1] >> 8) & 0xff] ^ T2[(st[2] >> 8) & 0xff] ^ T3[(st[3] >> 8) & 0xff] ^ rk[2];
    tmp[3] = T0[st[0] & 0xff] ^ T1[st[1] & 0xff] ^ T2[st[2] & 0xff] ^ T3[st[3] & 0xff] ^ rk[3];

    for (int k = 0; k < 4; k++) {
        st[k] = tmp[k];
    }
}

void SES32_Encrypt(byte pt[16], u32 rk[11][4], byte ct[16]) {
    u32 st[4], tmp[4];

    byte2state(pt, st);
    for (int k = 0; k < 4; k++) st[k] ^= rk[0][k];
    for (int r = 1; r <= 9; r++) SES32_EncRound(st, rk[r]);
    // 10라운드 
    tmp[0] = (T4[(st[0] >> 24) & 0xff] & 0xff000000) ^ (T4[(st[1] >> 24) & 0xff] & 0x00ff0000)
        ^ (T4[(st[2] >> 24) & 0xff] & 0x0000ff00) ^ (T4[(st[3] >> 24) & 0xff] & 0x000000ff) ^ rk[10][0];
    tmp[1] = (T4[(st[0] >> 16) & 0xff] & 0xff000000) ^ (T4[(st[1] >> 16) & 0xff] & 0x00ff0000)
        ^ (T4[(st[2] >> 16) & 0xff] & 0x0000ff00) ^ (T4[(st[3] >> 16) & 0xff] & 0x000000ff) ^ rk[10][1];
    tmp[2] = (T4[(st[0] >> 8) & 0xff] & 0xff000000) ^ (T4[(st[1] >> 8) & 0xff] & 0x00ff0000)
        ^ (T4[(st[2] >> 8) & 0xff] & 0x0000ff00) ^ (T4[(st[3] >> 8) & 0xff] & 0x000000ff) ^ rk[10][2];
    tmp[3] = (T4[st[0]& 0xff] & 0xff000000) ^ (T4[st[1] & 0xff] & 0x00ff0000)
        ^ (T4[st[2] & 0xff] & 0x0000ff00) ^ (T4[st[3] & 0xff] & 0x000000ff) ^ rk[10][3];

    state2byte(tmp, ct);

}

