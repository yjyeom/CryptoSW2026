void print_state(byte state[16]) {
    for (int i = 0; i < 16; i++) {
        printf("%02x", state[i]);
        if ((i % 4) == 3) printf(" ");
    }
    printf("\n");
}

// Kboxes
void KBoxes(byte state[16]) {
    for (int i = 0; i < 16; i++) state[i] = K[state[i]];
}


//Transpose of state 4x4 matrix
/*
 0  4  8 12     0  1  2  3
 1  5  9 13     4  5  6  7
 2  6 10 14 ->  8  9 10 11
 3  7 11 15    12 13 14 15
*/
void Transpose(byte state[16]) {
    byte temp;

    temp = state[1]; // 1-4
    state[1] = state[4]; state[4] = temp;
	temp = state[2]; // 2-8
    state[2] = state[8]; state[8] = temp;
	temp = state[3]; // 3-12
    state[3] = state[12]; state[12] = temp;
	temp = state[6]; // 6-9
    state[6] = state[9]; state[9] = temp;
	temp = state[7]; // 7-13
    state[7] = state[13]; state[13] = temp;
	temp = state[11]; // 11-14
    state[11] = state[14]; state[14] = temp;
}

//T-Column 연산 32비트 in[4] --> 32비트 out[4]
void TCol(byte in[4], byte out[4]) {
    byte MC[4][4] = {
        {0x02, 0x02, 0x03, 0x02},
        {0x02, 0x02, 0x02, 0x03},
        {0x03, 0x02, 0x02, 0x02},
        {0x02, 0x03, 0x02, 0x02} };
    for (int i = 0; i < 4; i++) {
        out[i] = 0x00;
        for (int j = 0; j < 4; j++) {
            //out[i] ^= MC[i][j] * in[j];
            out[i] ^= GF256_mul(MC[i][j], in[j]);
        }
    }
}

//T-Column 연산 - xtime()
void TCol_xtime(byte in[4], byte out[4]) {
    byte MC[4][4] = {
        {0x02, 0x02, 0x03, 0x02},
        {0x02, 0x02, 0x02, 0x03},
        {0x03, 0x02, 0x02, 0x02},
        {0x02, 0x03, 0x02, 0x02} };
    for (int i = 0; i < 4; i++) {
        out[i] = 0x00;
        for (int j = 0; j < 4; j++) {
            //out[i] ^= MC[i][j] * in[j];
            out[i] ^= GF256_mul(MC[i][j], in[j]);
        }
    }
    byte sum, sum2;
	sum = in[0] ^ in[1] ^ in[2] ^ in[3];
	sum2 = GF256_xtime(sum);
    out[0] = sum2 ^ in[2];
	out[1] = sum2 ^ in[3];
	out[2] = sum2 ^ in[0];
	out[3] = sum2 ^ in[1];
}


//TColums
void TColumns(byte state[16]) {
    byte in[4], out[4];
    for (int col = 0; col < 4; col++) {
        for (int i = 0; i < 4; i++) in[i] = state[4 * col + i];
        //TCol(in, out);
		TCol_xtime(in, out);
        for (int i = 0; i < 4; i++) state[4 * col + i] = out[i];
    }
}

//AddRoundKey
void AddRoundKey(byte state[16], byte rk[16]) {
    for (int i = 0; i < 16; i++) state[i] ^= rk[i];
}

//SES 암호화 함수
void SES8_Encrypt(byte pt[16], byte rk[11][16], byte ct[16]) {
    byte state[16];

    for (int i = 0; i < 16; i++) state[i] = pt[i];

    AddRoundKey(state, rk[0]); // rk[0] = {rk[0][0], rk[0][1], ... ,rk[0][15]}

    for (int r = 1; r <= 9; r++) {
        KBoxes(state);
        Transpose(state);
        TColumns(state);
        AddRoundKey(state, rk[r]);
    }

    KBoxes(state);
    Transpose(state);
    AddRoundKey(state, rk[10]);

    for (int i = 0; i < 16; i++) ct[i] = state[i];
}

//SES 복호화 함수
void SES8_Decrypt(byte ct[16], byte rk[11][16], byte pt[16]) {
    byte state[16];

    for (int i = 0; i < 16; i++) state[i] = ct[i];

    AddRoundKey(state, rk[10]);

    for (int r = 9; r >= 1; r--) {
        Transpose(state);
        KBoxes(state);
        AddRoundKey(state, rk[r]);
        TColumns(state);
    }
    Transpose(state);
    KBoxes(state);
    AddRoundKey(state, rk[0]);

    for (int i = 0; i < 16; i++) pt[i] = state[i];
}

//동치 복호화용 라운드키 만들기 rk -> rk'=Tcolumns^{-1}(rk)
void SES_EqInvKey(byte rk[11][16], byte eqrk[11][16]) {
    for (int r = 0; r < 11; r++) {
        for (int i = 0; i < 16; i++) {
            eqrk[r][i] = rk[r][i];
        }
    }
    for (int r = 1; r <= 9; r++) {
        TColumns(eqrk[r]);
    }
}

//SES 동치 복호화
void SES8_EqDecrypt(byte ct[16], byte eqrk[11][16], byte pt[16]) {
    byte state[16];

    for (int i = 0; i < 16; i++) state[i] = ct[i];

    AddRoundKey(state, eqrk[10]);

    for (int r = 9; r >= 1; r--) {
        KBoxes(state);
        Transpose(state);
        TColumns(state);
        AddRoundKey(state, eqrk[r]);
    }

    KBoxes(state);
    Transpose(state);
    AddRoundKey(state, eqrk[0]);

    for (int i = 0; i < 16; i++) pt[i] = state[i];
}

