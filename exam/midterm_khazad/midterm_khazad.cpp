// 키스케줄 
static u32 Rcon[10] = { 0x01000000, 0x02000000, 0x04000000, 0x08000000, 0x10000000,
                        0x20000000, 0x40000000, 0x80000000, 0x1b000000, 0x36000000 };

// 키스케줄용: (x0, x1, x2, x3) --> (x1, x2, x3, x0)
u32 RotWord(u32 w32) {
    return (w32 << 8) | (w32 >> 24);
}

// 키스케줄용: (x0, x1, x2, x3) --> (K[x0], K[x1], K[x2], K[x3])
u32 SubWord(u32 w32) {
    return (K[w32 >> 24] << 24) ^ (K[(w32 >> 16) & 0xff] << 16) ^ (K[(w32 >> 8) & 0xff] << 8) ^ K[w32 & 0xff];
}

// SES32 암호화 키스케줄 (128비트 암호키)
void SES32_Enc_KeySchedule(byte k[16], u32 rk[11][4]) {
    u32 tmp;
    int rcon_counter;

    for (int i = 0; i < 4; i++) {
        rk[0][i] = GETU32(k + 4 * i);
    }
    rcon_counter = 0;
    for (int i = 1; i < 11; i++) {
        tmp = rk[i - 1][3];
        for (int k = 0; k < 4; k++) {
            if (k == 0) {
                tmp = SubWord(RotWord(tmp)) ^ Rcon[rcon_counter]; // tmp = F(tmp)
                rcon_counter++;
            }
            rk[i][k] = rk[i - 1][k] ^ tmp;
            tmp = rk[i][k];
        }
    }
}

// SES32 (동치)복호화 키스케줄 
void SES32_Dec_KeySchedule(byte k[16], u32 rk[11][4]) {

    SES32_Enc_KeySchedule(k, rk);
    //1라운드 ~ 9라운드에 InvMixCol을 적용한다 !!!!! 
    // rk[1][],..., rk[9][] (rk[0][], rk[10][]은 그대로 둔다)
    // 
    // rk[i][0] --> InvMixCol() --> rk'[i][0]
    // rk[i][1] --> InvMixCol() --> rk'[i][1]
    // rk[i][2] --> InvMixCol() --> rk'[i][2]
    // rk[i][3] --> InvMixCol() --> rk'[i][3]
    // 
    // T4[x] = [ S[x], S[x], S[x], S[x] ]
    // Ti[] : TColumns(K( K() ))
    // 코드 이해하고, 간단히 만들어 보기 !!!!!
    for (int i = 1; i <= 9; i++) {
        rk[i][0] = T0[T4[(rk[i][0] >> 24)] & 0xff] ^ T1[T4[(rk[i][0] >> 16) & 0xff] & 0xff]
            ^ T2[T4[(rk[i][0] >> 8) & 0xff] & 0xff] ^ T3[T4[(rk[i][0]) & 0xff] & 0xff];
        rk[i][1] = T0[T4[(rk[i][1] >> 24)] & 0xff] ^ T1[T4[(rk[i][1] >> 16) & 0xff] & 0xff]
            ^ T2[T4[(rk[i][1] >> 8) & 0xff] & 0xff] ^ T3[T4[(rk[i][1]) & 0xff] & 0xff];
        rk[i][2] = T0[T4[(rk[i][2] >> 24)] & 0xff] ^ T1[T4[(rk[i][2] >> 16) & 0xff] & 0xff]
            ^ T2[T4[(rk[i][2] >> 8) & 0xff] & 0xff] ^ T3[T4[(rk[i][2]) & 0xff] & 0xff];
        rk[i][3] = T0[T4[(rk[i][3] >> 24)] & 0xff] ^ T1[T4[(rk[i][3] >> 16) & 0xff] & 0xff]
            ^ T2[T4[(rk[i][3] >> 8) & 0xff] & 0xff] ^ T3[T4[(rk[i][3]) & 0xff] & 0xff];
    }
}
