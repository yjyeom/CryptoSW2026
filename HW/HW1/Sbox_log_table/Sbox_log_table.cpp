void HW1_Prob5() {

    printf("=== [HW1 - Problem 5] ===\n");
    
    //5-(a)
    printf("=== [5-(a)]\n");
    
    int gen1 = 0x03;    
    byte gen1_pow;

    gen1_pow = 0x01;    
    for (int i = 0; i <= 255; i++) {
        printf("a^%d | 0x%02x \n", i, gen1_pow);
        gen1_pow = GF256_mul(gen1_pow, gen1);        
    }

    //5-(b)
    printf("\n=== [5-(b)]\n");
    byte x = 0xa1;
    byte y = 0x63;
    byte akx, aky, akz;
    int kx, ky, kz;
    int generator;

    generator = gen1;
    printf("Using generator = 0x%02x\n", generator);
    akx = generator;
    aky = generator;
    for (int i = 1; i <= 255; i++) {
        if (akx == x) {
            kx = i;
            break;
        }
        akx = GF256_mul(akx, generator);
    }
    for (int i = 1; i <= 255; i++) {
        if (aky == y) {
            ky = i;
            break;
        }
        aky = GF256_mul(aky, generator);
    }
    kz = (kx + ky) % 255;
    akz = 1;
    for (int i = 1; i <= kz; i++) {
        akz = GF256_mul(akz, generator);
    }
    printf(" x = 0x%02x = 0x%02x ^ %d \n", x, generator, kx);
    printf(" y = 0x%02x = 0x%02x ^ %d \n", y, generator, ky);
    printf(" z = x*y = 0x%02x = 0x%02x ^ %d \n", akz, generator, kz);
    //확인용! 
    // printf(" x*y = 0x%02x * 0x%02x = 0x%02x\n", x, y, GF_mul(x, y));

    //5-(c)
    printf("\n=== [5-(c)]\n");
    byte base_x = gen1;
    byte pow_x = 1;
    byte LogTable[256];
    LogTable[0] = 0; //0은 예외
    for (int i = 1; i <= 255; i++) { // 실제로 i<=254까지만 해도 된다 (a^255=1)
        pow_x = GF256_mul(base_x, pow_x);
        LogTable[pow_x] = i;
    }
    LogTable[1] = 0; // a^0 = a^(255 mod (2^8-1)) = 1

    //LogTable의 역함수 테이블 만들기
    byte ExpTable[256];
    for (int i = 0; i < 256; i++) {
        ExpTable[LogTable[i]] = i;
    }
    ExpTable[255] = 0x01;  // a^255 = 1 이므로 (LogTable[]에는 255가 없다)
    printf("byte LogTable[256] = {");
    for (int i = 0; i < 256; i++) {
        if ((i % 16) == 0) printf("\n");
        if (i < 255) {
            printf(" 0x%02x,", LogTable[i]);
        }
        else {
            printf(" 0x%02x};\n\n", LogTable[i]);
        }
    }
    
    printf("byte ExpTable[256] = {");
    for (int i = 0; i < 256; i++) {
        if ((i % 16) == 0) printf("\n");
        if (i < 255) {
            printf(" 0x%02x,", ExpTable[i]);
        }
        else {
            printf(" 0x%02x};\n\n", ExpTable[i]);
        }
    }
    
    //5-(d)
    printf("\n=== [5-(d)]\n");
    x = 0xa1;
    y = 0x63;
    byte z;
    z = GF_mul_cycle(x, y);
    printf(" x = 0x%02x = 0x%02x ^ %d \n", x, generator, kx);
    printf(" y = 0x%02x = 0x%02x ^ %d \n", y, generator, ky);
    printf(" z = %02x = x*y = 0x%02x = 0x%02x ^ %d \n", z, akz, generator, kz);

}



